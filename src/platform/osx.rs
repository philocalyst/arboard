/// Marks data as sensitive (such as a password), so it isn't recorded by clipboard history tools.
///
/// See <http://nspasteboard.org/> for details about the community standard.
const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";
/// Marks data as transient, for example data placed onto the pasteboard only to perform an
/// automated paste, which clipboard history tools shouldn't record.
const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
/// Marks data as generated by an application rather than explicitly copied by the user.
const AUTO_GENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";
